function multiplyAffine(a, b) {
  return [
    a[0] * b[0] + a[2] * b[1],
    a[1] * b[0] + a[3] * b[1],
    a[0] * b[2] + a[2] * b[3],
    a[1] * b[2] + a[3] * b[3],
    a[0] * b[4] + a[2] * b[5] + a[4],
    a[1] * b[4] + a[3] * b[5] + a[5],
  ];
}

function framePlacement(design, resolution) {
  const scale = Math.min(resolution[0] / design[0], resolution[1] / design[1]);
  const ox = (resolution[0] - design[0] * scale) / 2;
  const oy = (resolution[1] - design[1] * scale) / 2;
  return { scale, ox, oy, matrix: [scale, 0, 0, scale, ox, oy] };
}

function pixelScissor(ox, oy, resolution) {
  const x = Math.ceil(ox);
  const y = Math.ceil(oy);
  return {
    x,
    y,
    width: Math.max(0, Math.floor(resolution[0] - ox) - x),
    height: Math.max(0, Math.floor(resolution[1] - oy) - y),
  };
}

function intersectPixelRects(a, b) {
  const x = Math.max(a.x, b.x);
  const y = Math.max(a.y, b.y);
  const right = Math.min(a.x + a.width, b.x + b.width);
  const bottom = Math.min(a.y + a.height, b.y + b.height);
  return {
    x,
    y,
    width: Math.max(0, right - x),
    height: Math.max(0, bottom - y),
  };
}

function targetWindow(resolution, scissor) {
  return intersectPixelRects(scissor, {
    x: 0,
    y: 0,
    width: resolution[0],
    height: resolution[1],
  });
}

function childPixelsToParent(uniform, childWidth, childHeight) {
  const scaleX = uniform.rect[2] / childWidth;
  const scaleY = uniform.rect[3] / childHeight;
  const camera = [
    uniform.cameraX[0],
    uniform.cameraY[0],
    uniform.cameraX[1],
    uniform.cameraY[1],
    uniform.cameraX[2],
    uniform.cameraY[2],
  ];
  const command = [
    uniform.transform[0],
    0,
    0,
    uniform.transform[1],
    uniform.transform[2],
    uniform.transform[3],
  ];
  return multiplyAffine(
    camera,
    multiplyAffine(
      command,
      multiplyAffine(
        [1, 0, 0, 1, uniform.rect[0], uniform.rect[1]],
        [scaleX, 0, 0, scaleY, 0, 0],
      ),
    ),
  );
}

function clipPolygonToRect(points, rect) {
  const right = rect.x + rect.width;
  const bottom = rect.y + rect.height;
  const crossX = (a, b, x) => {
    const dx = b[0] - a[0];
    if (dx === 0) return undefined;
    const y = a[1] + ((x - a[0]) / dx) * (b[1] - a[1]);
    return Number.isFinite(y) ? [x, y] : undefined;
  };
  const crossY = (a, b, y) => {
    const dy = b[1] - a[1];
    if (dy === 0) return undefined;
    const x = a[0] + ((y - a[1]) / dy) * (b[0] - a[0]);
    return Number.isFinite(x) ? [x, y] : undefined;
  };
  const edges = [
    [(point) => point[0] >= rect.x, (a, b) => crossX(a, b, rect.x)],
    [(point) => point[0] <= right, (a, b) => crossX(a, b, right)],
    [(point) => point[1] >= rect.y, (a, b) => crossY(a, b, rect.y)],
    [(point) => point[1] <= bottom, (a, b) => crossY(a, b, bottom)],
  ];
  let poly = points.map((point) => [...point]);
  for (const [inside, cross] of edges) {
    if (!poly.length) return [];
    const out = [];
    let previous = poly[poly.length - 1];
    let previousIn = inside(previous);
    for (const point of poly) {
      const pointIn = inside(point);
      if (pointIn !== previousIn) {
        const hit = cross(previous, point);
        if (!hit) return undefined;
        out.push(hit);
      }
      if (pointIn) out.push(point);
      previous = point;
      previousIn = pointIn;
    }
    poly = out;
  }
  return poly;
}

function boundsOfPoints(points) {
  const xs = points.map((point) => point[0]);
  const ys = points.map((point) => point[1]);
  const minX = Math.min(...xs);
  const minY = Math.min(...ys);
  return {
    x: minX,
    y: minY,
    width: Math.max(...xs) - minX,
    height: Math.max(...ys) - minY,
  };
}

function uploadedCorners(rect, transform, cameraX, cameraY) {
  const [x, y, width, height] = rect.map(Math.fround);
  const [sx, sy, tx, ty] = transform.map(Math.fround);
  const camX = cameraX.map(Math.fround);
  const camY = cameraY.map(Math.fround);
  return [
    [0, 0],
    [1, 0],
    [1, 1],
    [0, 1],
  ].map(([u, v]) => {
    const worldX = (x + u * width) * sx + tx;
    const worldY = (y + v * height) * sy + ty;
    return [
      camX[0] * worldX + camX[1] * worldY + camX[2],
      camY[0] * worldX + camY[1] * worldY + camY[2],
    ];
  });
}

function clipLevel(bounds, transform, parentFrame, parentResolution) {
  const childWidth = Math.max(1, Math.ceil(bounds.width * parentFrame.scale));
  const childHeight = Math.max(1, Math.ceil(bounds.height * parentFrame.scale));
  const childResolution = [childWidth, childHeight];
  const childFrame = framePlacement([bounds.width, bounds.height], childResolution);
  const scissor = pixelScissor(childFrame.ox, childFrame.oy, childResolution);
  const uniform = {
    rect: [bounds.x, bounds.y, bounds.width, bounds.height].map(Math.fround),
    transform: transform.map(Math.fround),
    resolution: [...parentResolution].map(Math.fround),
    cameraX: [
      parentFrame.matrix[0],
      parentFrame.matrix[2],
      parentFrame.matrix[4],
    ].map(Math.fround),
    cameraY: [
      parentFrame.matrix[1],
      parentFrame.matrix[3],
      parentFrame.matrix[5],
    ].map(Math.fround),
  };
  return {
    childResolution,
    childFrame,
    scissor,
    window: targetWindow(childResolution, scissor),
    matrix: childPixelsToParent(uniform, childWidth, childHeight),
  };
}

function projectLeaf(rect, transform, chain, rootWindow) {
  const inner = chain[0];
  let polygon = uploadedCorners(
    rect,
    transform,
    [
      inner.childFrame.matrix[0],
      inner.childFrame.matrix[2],
      inner.childFrame.matrix[4],
    ],
    [
      inner.childFrame.matrix[1],
      inner.childFrame.matrix[3],
      inner.childFrame.matrix[5],
    ],
  );
  for (const level of chain) {
    const clipped = clipPolygonToRect(polygon, level.window);
    if (!clipped?.length) throw Error("clip projection produced no coverage");
    polygon = clipped.map((point) => [
      level.matrix[0] * point[0] +
        level.matrix[2] * point[1] +
        level.matrix[4],
      level.matrix[1] * point[0] +
        level.matrix[3] * point[1] +
        level.matrix[5],
    ]);
  }
  const clipped = clipPolygonToRect(polygon, rootWindow);
  if (!clipped?.length) throw Error("root scissor removed the leaf");
  return boundsOfPoints(clipped);
}

/** Ideal quads from float32 uniforms, ceil child targets, and scissor. Not pixels. */
function expectedClipQuads() {
  const rootResolution = [320, 180];
  const rootFrame = framePlacement(rootResolution, rootResolution);
  const rootWindow = targetWindow(
    rootResolution,
    pixelScissor(rootFrame.ox, rootFrame.oy, rootResolution),
  );
  const main = clipLevel(
    { x: 0, y: 0, width: 80, height: 40 },
    [1, 1, 40, 30],
    rootFrame,
    rootResolution,
  );
  const outer = clipLevel(
    { x: 0, y: 0, width: 80, height: 40 },
    [1, 1, 180, 30],
    rootFrame,
    rootResolution,
  );
  const inner = clipLevel(
    { x: 0, y: 0, width: 30.5, height: 17.25 },
    [1, 1, 10.25, 4.5],
    outer.childFrame,
    outer.childResolution,
  );
  const at = (scroll) => ({
    red: projectLeaf([0, 0, 60, 40], [1, 1, scroll, 0], [main], rootWindow),
    blue: projectLeaf([60, 0, 60, 40], [1, 1, scroll, 0], [main], rootWindow),
  });
  return {
    main,
    outer,
    inner,
    a: at(0),
    b: at(-40),
    nested: projectLeaf(
      [0, 0, 40, 20],
      [-1, 1, 20, 0],
      [inner, outer],
      rootWindow,
    ),
  };
}

function insideMargin(bounds, point) {
  return Math.min(
    point[0] - bounds.x,
    bounds.x + bounds.width - point[0],
    point[1] - bounds.y,
    bounds.y + bounds.height - point[1],
  );
}

function outsideMargin(bounds, point) {
  const dx = Math.max(
    bounds.x - point[0],
    point[0] - (bounds.x + bounds.width),
    0,
  );
  const dy = Math.max(
    bounds.y - point[1],
    point[1] - (bounds.y + bounds.height),
    0,
  );
  return Math.max(dx, dy);
}

function unionQuad(left, right) {
  const x = Math.min(left.x, right.x);
  const y = Math.min(left.y, right.y);
  const rightEdge = Math.max(left.x + left.width, right.x + right.width);
  const bottom = Math.max(left.y + left.height, right.y + right.height);
  return { x, y, width: rightEdge - x, height: bottom - y };
}

function interiorSample(bounds, margin) {
  const point = [
    Math.round(bounds.x + bounds.width / 2),
    Math.round(bounds.y + bounds.height / 2),
  ];
  const clearance = insideMargin(bounds, point);
  assert.ok(
    clearance >= margin,
    `sample ${point} is only ${clearance}px inside ${JSON.stringify(bounds)}`,
  );
  return point;
}

