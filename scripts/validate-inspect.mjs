/** Two float32 endpoints can each move by one ulp; the offset is staged through Math.fround. */
function float32UniformTolerance(...values) {
  let ulp = 0;
  for (const value of values) {
    const rounded = Math.fround(value);
    const magnitude = Math.abs(rounded);
    const step =
      magnitude === 0
        ? 2 ** -149
        : 2 ** (Math.floor(Math.log2(magnitude)) - 23);
    ulp = Math.max(ulp, step);
  }
  return 2 * ulp;
}

function assertFloat32Close(actual, expected, label) {
  const tolerance = float32UniformTolerance(actual, expected);
  assert.ok(
    Math.abs(actual - expected) <= tolerance,
    `${label}: ${actual} expected ${expected} within ${tolerance}`,
  );
}

function assertQuadEqual(left, right, label) {
  for (const key of ["x", "y", "width", "height"])
    assertFloat32Close(left[key], right[key], `${label}.${key}`);
}

function clipToViewport(bounds, resolution) {
  const x0 = Math.min(bounds.x, bounds.x + bounds.width);
  const x1 = Math.max(bounds.x, bounds.x + bounds.width);
  const y0 = Math.min(bounds.y, bounds.y + bounds.height);
  const y1 = Math.max(bounds.y, bounds.y + bounds.height);
  const x = Math.max(x0, 0);
  const y = Math.max(y0, 0);
  const right = Math.min(x1, resolution[0]);
  const bottom = Math.min(y1, resolution[1]);
  const width = right - x;
  const height = bottom - y;
  if (width > 0 && height > 0) return { x, y, width, height };
  return { x, y, width: 0, height: 0 };
}

